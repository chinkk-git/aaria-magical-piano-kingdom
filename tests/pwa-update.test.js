const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {APP_BUILD,parseBuildId,compareBuilds,loadedInterfaceBuilds,interfaceMatchesBuild,shouldRefreshStaleInterface}=require('../pwa-update.js');
const root=path.resolve(__dirname,'..');
const index=fs.readFileSync(path.join(root,'index.html'),'utf8');
const worker=fs.readFileSync(path.join(root,'sw.js'),'utf8');
const deploy=fs.readFileSync(path.join(root,'.github/workflows/piano-deploy.yml'),'utf8');
assert.equal(parseBuildId(worker),APP_BUILD,'page updater and current service worker share the build id');
assert.equal(APP_BUILD,'aaria-piano-v2.1.14','the corrected interface ships as a new release build');
const expectedUi=APP_BUILD;
assert.ok(index.includes('v2.1-ui.js?v='+expectedUi),'production shell pins the V2.1 script to its release build');
assert.ok(index.includes('v2.1-ui.css?v='+expectedUi),'production shell pins the V2.1 stylesheet to its release build');
assert.ok(index.includes('pwa-update.js?v=aaria-pwa-update-1.3'),'production shell loads the stale-interface-aware updater');
assert.ok(worker.includes('./v2.1-ui.js?v='+expectedUi),'offline shell caches the matching V2.1 script');
assert.ok(worker.includes('./v2.1-ui.css?v='+expectedUi),'offline shell caches the matching V2.1 stylesheet');
assert.ok(worker.includes('./pwa-update.js?v=aaria-pwa-update-1.3'),'offline shell caches the matching updater');
const currentDoc={querySelector(selector){return selector.startsWith('script')?{getAttribute:()=> './v2.1-ui.js?v='+expectedUi}:{getAttribute:()=> './v2.1-ui.css?v='+expectedUi}}};
const staleDoc={querySelector(selector){return selector.startsWith('script')?{getAttribute:()=> './v2.1-ui.js?v=aaria-piano-v2.1.13'}:{getAttribute:()=> './v2.1-ui.css?v=aaria-piano-v2.1.13'}}};
const currentAssets=loadedInterfaceBuilds(currentDoc),staleAssets=loadedInterfaceBuilds(staleDoc);
assert.ok(interfaceMatchesBuild(currentAssets,expectedUi),'current page, script, style, and release agree');
assert.ok(!interfaceMatchesBuild(staleAssets,expectedUi),'a service-worker version alone does not certify stale V2.1 UI assets');
assert.ok(shouldRefreshStaleInterface(staleAssets,expectedUi,expectedUi),'same service-worker build with stale screen assets forces a reload');
assert.ok(!shouldRefreshStaleInterface(staleAssets,'aaria-piano-v2.1.13',expectedUi),'do not reload while the newer service worker is still pending installation');
assert.equal(compareBuilds('aaria-piano-v1.20.4','aaria-piano-v1.20.3'),1);
assert.equal(compareBuilds('aaria-piano-v1.20.4','aaria-piano-v1.20.4'),0);
assert.equal(compareBuilds('aaria-piano-v1.19.9','aaria-piano-v1.20.0'),-1);
assert.equal(compareBuilds('invalid','aaria-piano-v1.20.4'),null);
assert.ok(index.includes('id="checkAppUpdate"'),'Settings exposes Check for Updates');
assert.ok(index.includes('id="restartAppUpdate"'),'Settings exposes a conditional restart action');
assert.ok(index.includes('id="downloadAppDiagnostics"'),'Settings exposes a local diagnostics download');
assert.ok(index.includes('pwa-diagnostics.js?v=aaria-pwa-diagnostics-1.2'),'diagnostics logger is loaded');
assert.ok(worker.includes('./pwa-diagnostics.js?v=aaria-pwa-diagnostics-1.2'),'diagnostics logger is cached for offline access');
assert.ok(index.includes('pwa-update.js?v=aaria-pwa-update-1.2'));
assert.ok(worker.includes('./pwa-update.js?v=aaria-pwa-update-1.2'),'service worker precaches the updater');
assert.ok(deploy.includes('pwa-update.js'),'Pages build includes the updater source');
assert.ok(worker.includes('AARIA_GET_BUILD'),'installed service worker reports its actual build');
assert.ok(worker.includes('AARIA_ACTIVATE_UPDATE'),'waiting update can be activated by explicit user action');
const updater=fs.readFileSync(path.join(root,'pwa-update.js'),'utf8');
assert.match(updater,/Downloading app update…/,'Settings reports when the app shell is downloading');
assert.match(updater,/Update ready\. Restart App/,'Settings exposes a clear restart-ready state');
assert.match(updater,/120000/,'slow mobile updates get enough time to finish');
assert.match(updater,/AARIA_SW_INSTALL_ERROR/,'service worker install failures are recorded');
assert.match(fs.readFileSync(path.join(root,'pwa-diagnostics.js'),'utf8'),/aaria-piano-diagnostics-v1/,'diagnostics are kept locally');
assert.ok(index.includes('excludes score photos, song notes and saved-song contents'),'Settings explains the local diagnostics file contents');
assert.ok(deploy.includes('pwa-diagnostics.js'),'Pages build includes the local diagnostics logger');
console.log('PWA update build and Settings invariants passed');
